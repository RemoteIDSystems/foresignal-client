/**
 * A situation's Overview: the deterministic summary, the labeled LLM brief when there is one, what
 * changed over the chosen window, the evidence by signal family with the corroboration roll-up, the
 * basis of its status and severity, and the latest timeline entries.
 */
export function SituationOverview({
  analysis,
  rangeLabel,
  onOpen,
}: {
  analysis: SituationAnalysis;
  rangeLabel: string;
  onOpen: (ref: string) => void;
}) {
  const { situation, changes, timeline } = analysis;
  const families = [...situation.evidence.families].sort((a, b) => b.count - a.count);
  const top = Math.max(1, ...families.map((family) => family.count));
  const corroboration = situation.evidence.corroboration;
  const changed = changes ? changesLines(changes) : undefined;
  const rows = useMemo(() => timelineRows(timeline).slice(0, OVERVIEW_TIMELINE_ROWS), [timeline]);
  return (
    <div className={styles.grid} data-testid="situation-overview">
      <section className={styles.card} aria-labelledby="overview-summary">
        <h2 id="overview-summary" className={styles.cardTitle}>
          Summary
        </h2>
        <p className={styles.text}>{situation.inference.summary || situation.summary}</p>
        {situation.speculation.brief && (
          <div className={styles.speculation} data-testid="situation-brief">
            <Badge tone="warning">Speculation</Badge>
            <p className={styles.text}>{situation.speculation.brief}</p>
            <span className={styles.muted}>
              Generated by a language model
              {situation.speculation.briefModel ? ` (${situation.speculation.briefModel})` : ''}
              {situation.speculation.briefGeneratedAt
                ? `, ${utcText(situation.speculation.briefGeneratedAt)}`
                : ''}
              .
            </span>
          </div>
        )}
        <dl className={styles.facts}>
          <dt>Theme</dt>
          <dd>{prettifyId(situation.theme)}</dd>
          <dt>Severity</dt>
          <dd>
            <Badge tone={severityTone(situation.severity)}>{situation.severity}</Badge>{' '}
            {situation.inference.severityBasis}
          </dd>
          <dt>Status</dt>
          <dd>{situation.inference.statusBasis}</dd>
          <dt>Regions</dt>
          <dd>{situation.regionCodes.join(', ') || '—'}</dd>
          <dt>Members</dt>
          <dd>{situation.memberCount.toLocaleString('en-US')}</dd>
        </dl>
      </section>
      <section
        className={styles.card}
        aria-labelledby="overview-changes"
        data-testid="what-changed"
      >
        <h2 id="overview-changes" className={styles.cardTitle}>
          What changed ({rangeLabel})
        </h2>
        {changed === undefined && <p className={styles.muted}>The changes did not load.</p>}
        {changed?.length === 0 && <p className={styles.muted}>Nothing changed in this window.</p>}
        {changed && changed.length > 0 && (
          <ul className={styles.bulletList}>
            {changed.map((line) => (
              <li key={line}>{line}</li>
            ))}
          </ul>
        )}
      </section>
      <section className={styles.card} aria-labelledby="overview-evidence">
        <h2 id="overview-evidence" className={styles.cardTitle}>
          Evidence by signal family
        </h2>
        {families.length === 0 && <p className={styles.muted}>No members yet.</p>}
        {families.map((family) => (
          <div key={family.family} className={styles.familyRow} data-family={family.family}>
            <span>{prettifyId(family.family)}</span>
            <span className={styles.muted}>
              {family.count.toLocaleString('en-US')}
              {family.coreCount !== undefined ? ` (${family.coreCount} core)` : ''}
            </span>
            <span
              className={styles.familyBar}
              style={{ width: `${(family.count / top) * 100}%` }}
              aria-hidden="true"
            />
          </div>
        ))}
        <p className={styles.muted}>
          Corroborated {corroboration.corroborated}, uncorroborated {corroboration.uncorroborated}
          {corroboration.unknown ? `, unknown ${corroboration.unknown}` : ''}.
        </p>
      </section>
      <section className={styles.card} aria-labelledby="overview-timeline">
        <h2 id="overview-timeline" className={styles.cardTitle}>
          Latest ({rangeLabel})
        </h2>
        <TimelineList rows={rows} onOpen={onOpen} />
      </section>
    </div>
  );
}

/** Timeline rows, as the mock's CONFLICT TIMELINE lists them; a member's row opens its object. */
export function TimelineList({
  rows,
  onOpen,
}: {
  rows: readonly TimelineRow[];
  onOpen: (ref: string) => void;
}) {
  if (rows.length === 0) return <p className={styles.muted}>No entries in this window.</p>;
  return (
    <ul className={styles.rows} aria-label="Timeline" data-testid="timeline-rows">
      {rows.map((row) => {
        const content = (
          <>
            <span className={styles.rowDay}>{dayText(row.at)}</span>
            <span className={styles.rowTitle} title={utcText(row.at)}>
              {row.title}
            </span>
            <Badge tone="info">{prettifyId(row.tag)}</Badge>
            {row.severity ? (
              <Badge tone={severityTone(row.severity)}>{row.severity}</Badge>
            ) : (
              <span />
            )}
          </>
        );
        const ref = row.ref;
        return (
          <li key={row.key} className={styles.row}>
            {ref ? (
              <button type="button" className={styles.rowButton} onClick={() => onOpen(ref)}>
                {content}
              </button>
            ) : (
              content
            )}
          </li>
        );
      })}
    </ul>
  );
}

type RoleFilter = 'all' | 'core' | 'context';

/**
 * A situation's Entities tab: its pinned members in a table (title, type, signal family, role,
 * corroboration, when observed), filtered by role and family. A member opens its object; an
 * intelligence event opens its detail (`getIntelEvent`) beside the table.
 */
export function MembersTab({
  api,
  members,
  onOpen,
}: {
  api: ForesignalClient | undefined;
  members: readonly SituationMember[];
  onOpen: (ref: string) => void;
}) {
  const [role, setRole] = useState<RoleFilter>('all');
  const [family, setFamily] = useState('');
  const [event, setEvent] = useState<{ id: string; value?: IntelligenceEvent; error?: string }>();
  const families = useMemo(
    () => [...new Set(members.map((m) => m.signalFamily).filter((f): f is string => !!f))].sort(),
    [members],
  );
  const shown = members.filter(
    (member) =>
      (role === 'all' || member.role === role) && (!family || member.signalFamily === family),
  );
  const open = (member: SituationMember) => {
    if (member.memberType !== 'intel_event' || !api) {
      onOpen(member.objectRef);
      return;
    }
    setEvent({ id: member.ref });
    getIntelEvent(api, member.ref).then(
      (value) =>
        setEvent((current) => (current?.id === member.ref ? { ...current, value } : current)),
      (error: unknown) =>
        setEvent((current) =>
          current?.id === member.ref
            ? { ...current, error: error instanceof Error ? error.message : 'It did not load.' }
            : current,
        ),
    );
  };
  return (
    <div data-testid="members-tab">
      <div className={styles.toolbar}>
        <label>
          <span className={styles.visuallyHidden}>Role</span>
          <select
            className={styles.select}
            value={role}
            onChange={(e) => setRole(e.target.value as RoleFilter)}
          >
            <option value="all">All roles</option>
            <option value="core">Core</option>
            <option value="context">Context</option>
          </select>
        </label>
        <label>
          <span className={styles.visuallyHidden}>Signal family</span>
          <select
            className={styles.select}
            value={family}
            onChange={(e) => setFamily(e.target.value)}
          >
            <option value="">All families</option>
            {families.map((f) => (
              <option key={f} value={f}>
                {prettifyId(f)}
              </option>
            ))}
          </select>
        </label>
        <span className={styles.muted}>
          {shown.length.toLocaleString('en-US')} of {members.length.toLocaleString('en-US')}
        </span>
      </div>
      {members.length === 0 ? (
        <p className={styles.muted}>No members are pinned to this situation.</p>
      ) : (
        <div className={styles.tableWrap}>
          <table className={styles.table} aria-label="Members">
            <thead>
              <tr>
                <th>Member</th>
                <th>Type</th>
                <th>Family</th>
                <th>Role</th>
                <th>Corroboration</th>
                <th>Observed</th>
              </tr>
            </thead>
            <tbody>
              {shown.map((member) => (
                <tr key={member.id} data-member-type={member.memberType}>
                  <td>
                    <button
                      type="button"
                      className={styles.linkButton}
                      onClick={() => open(member)}
                    >
                      {member.title ?? member.kind ?? member.ref}
                    </button>
                  </td>
                  <td>{prettifyId(member.memberType)}</td>
                  <td>{member.signalFamily ? prettifyId(member.signalFamily) : '—'}</td>
                  <td>{member.role === 'core' ? 'Core' : 'Context'}</td>
                  <td>{member.corroboration}</td>
                  <td>{utcText(member.observedAt)}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
      {event && (
        <aside className={styles.drawer} aria-label="Intelligence event" data-testid="event-detail">
          <div className={styles.drawerHead}>
            <h2 className={styles.cardTitle}>{event.value?.title ?? 'Intelligence event'}</h2>
            <IconButton
              label="Close event"
              icon={<X size={15} />}
              onClick={() => setEvent(undefined)}
            />
          </div>
          {event.error && <p className={styles.error}>{event.error}</p>}
          {!event.value && !event.error && <p className={styles.muted}>Loading…</p>}
          {event.value && <EventDetail event={event.value} onOpen={onOpen} />}
        </aside>
      )}
    </div>
  );
}

/** An intelligence event member's object ref: a record's or an alert's; undefined otherwise. */
function eventMemberRef(member: IntelEventMember): string | undefined {
  if (member.memberType === 'record' && member.sourceId && member.externalId) {
    return recordRef(member.sourceId, member.externalId, member.seq ?? undefined);
  }
  if (member.memberType === 'alert' && member.alertId != null) return `alert:${member.alertId}`;
  return undefined;
}

/**
 * An intelligence event's type, status and severity, its confidence and evidence quality, the
 * inference's explanation, and its members (supporting, contradicting or context).
 */
function EventDetail({
  event,
  onOpen,
}: {
  event: IntelligenceEvent;
  onOpen: (ref: string) => void;
}) {
  const { inference, evidence } = event;
  return (
    <>
      <div className={styles.titleRow}>
        <Badge tone="info">{prettifyId(event.type)}</Badge>
        <Badge tone="neutral">{event.status}</Badge>
        <Badge tone={severityTone(event.severity)}>{event.severity}</Badge>
      </div>
      <p className={styles.muted}>
        Confidence {Math.round(inference.confidence * 100)}% ({inference.confidenceLabel}), evidence{' '}
        {inference.evidenceQuality}.
      </p>
      <p className={styles.text}>{inference.explanation}</p>
      <h3 className={styles.cardTitle}>Members ({evidence.memberCount})</h3>
      <ul className={styles.rows}>
        {evidence.members.map((member) => {
          const ref = eventMemberRef(member);
          const label = member.kind ?? member.externalId ?? member.id;
          return (
            <li key={member.id} className={styles.listMeta} data-role={member.role}>
              <Badge tone={member.role === 'contradicting' ? 'danger' : 'neutral'}>
                {member.role}
              </Badge>
              {ref ? (
                <button type="button" className={styles.linkButton} onClick={() => onOpen(ref)}>
                  {label}
                </button>
              ) : (
                label
              )}
            </li>
          );
        })}
      </ul>
    </>
  );
}
